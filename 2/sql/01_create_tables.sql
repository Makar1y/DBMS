CREATE TABLE client (
    id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(50)  NOT NULL,
    surname     varchar(50)  NOT NULL,
    email       varchar(100) NOT NULL,
    phone       varchar(20),
    city        varchar(50),
    street      varchar(100),
    home_nr     varchar(10),

    CONSTRAINT uq_client_email UNIQUE (email),
    CONSTRAINT chk_client_email_format CHECK (
        email ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'
    ),
    CONSTRAINT chk_client_phone_format CHECK (
        phone IS NULL OR phone ~ '^\+?[0-9 ()-]{8,20}$'
    ),
    CONSTRAINT chk_client_home_nr CHECK (
        home_nr IS NULL OR home_nr ~ '^[0-9]+[A-Za-z]?$'
    )
);

CREATE TABLE client_category (
    client_id integer     NOT NULL REFERENCES client(id) ON DELETE CASCADE,
    category  varchar(5)  NOT NULL,

    PRIMARY KEY (client_id, category),
    CONSTRAINT chk_client_category_format CHECK (category ~ '^[A-Z0-9]{1,3}$')
);

CREATE TABLE location (
    id       integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     varchar(100) NOT NULL,
    city     varchar(50)  NOT NULL,
    address  varchar(150),

    CONSTRAINT chk_location_name_not_blank CHECK (length(btrim(name)) > 0),
    CONSTRAINT chk_location_city_not_blank CHECK (length(btrim(city)) > 0)
);

CREATE TABLE car (
    id                 integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    required_category  varchar(5)   NOT NULL,
    registration_nr    varchar(12)  NOT NULL,
    brand              varchar(50)  NOT NULL,
    model              varchar(50)  NOT NULL,
    production_year    smallint     NOT NULL,
    price              numeric(8,2) NOT NULL,
    status             varchar(20)  NOT NULL DEFAULT 'available',

    CONSTRAINT uq_car_registration_nr UNIQUE (registration_nr),
    CONSTRAINT chk_car_required_category CHECK (required_category ~ '^[A-Z0-9]{1,3}$'),
    CONSTRAINT chk_car_registration_format CHECK (registration_nr ~ '^[A-Z0-9-]{3,12}$'),
    CONSTRAINT chk_car_brand_not_blank CHECK (length(btrim(brand)) > 0),
    CONSTRAINT chk_car_model_not_blank CHECK (length(btrim(model)) > 0),
    CONSTRAINT chk_car_price_positive CHECK (price > 0),
    CONSTRAINT chk_car_year_range CHECK (production_year BETWEEN 1950 AND 2100),
    CONSTRAINT chk_car_status CHECK (
        status IN ('available', 'reserved', 'maintenance', 'retired')
    )
);

CREATE TABLE reservation (
    id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id   integer      NOT NULL REFERENCES client(id) ON DELETE RESTRICT,
    car_id      integer      NOT NULL REFERENCES car(id) ON DELETE RESTRICT,
    start_time  timestamp    NOT NULL,
    end_time    timestamp    NOT NULL,
    status      varchar(20)  NOT NULL DEFAULT 'active',

    CONSTRAINT chk_reservation_period CHECK (end_time > start_time),
    CONSTRAINT chk_reservation_status CHECK (
        status IN ('active', 'cancelled', 'completed', 'no_show')
    )
);

CREATE TABLE car_location (
    car_id       integer   NOT NULL REFERENCES car(id) ON DELETE RESTRICT,
    location_id  integer   NOT NULL REFERENCES location(id) ON DELETE RESTRICT,
    from_time    timestamp NOT NULL,
    to_time      timestamp,

    PRIMARY KEY (car_id, location_id, from_time),
    CONSTRAINT chk_car_location_period CHECK (
        to_time IS NULL OR to_time > from_time
    )
);
